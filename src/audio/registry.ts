const REGISTRY_BY_ID = new Map<string, SfxAssetEntry>(
  SFX_ASSET_REGISTRY.map((entry) => [entry.id, entry]),
);

const REGISTRY_BY_LEGACY_CATEGORY = new Map<SoundEffectCategory, SfxAssetEntry>(
  SFX_ASSET_REGISTRY.filter((e): e is SfxAssetEntry & { legacyCategory: SoundEffectCategory } =>
    Boolean(e.legacyCategory),
  ).map((e) => [e.legacyCategory, e]),
);

export const getSfxAsset = (id: string): SfxAssetEntry | undefined =>
  REGISTRY_BY_ID.get(id);

export const requireSfxAsset = (id: string): SfxAssetEntry => {
  const entry = REGISTRY_BY_ID.get(id);
  if (!entry) {
    throw new Error(`SFX asset "${id}" was not found in SFX_ASSET_REGISTRY.`);
  }
  return entry;
};

export const listSfxByCategory = (category: SfxDomainCategory): SfxAssetEntry[] =>
  SFX_ASSET_REGISTRY.filter((entry) => entry.category === category);

export const resolveSfxAssetByLegacyCategory = (
  category: SoundEffectCategory,
): SfxAssetEntry | undefined => REGISTRY_BY_LEGACY_CATEGORY.get(category);
